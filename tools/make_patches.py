"""Diff the clean exe against the patched exe and emit src/patches.h (VA, original bytes, new bytes)."""
import struct,sys
a=open(sys.argv[1],'rb').read(); b=open(sys.argv[2],'rb').read(); out=sys.argv[3]
assert len(a)==len(b)
pe=struct.unpack_from('<I',a,0x3c)[0]; n=struct.unpack_from('<H',a,pe+6)[0]; opt=struct.unpack_from('<H',a,pe+20)[0]
base=struct.unpack_from('<I',a,pe+0x34)[0]; sh=pe+24+opt
secs=[struct.unpack_from('<8sIIII',a,sh+40*i) for i in range(n)]
hdr_end=min(s[4] for s in secs)
def va(off):
    for nm,vs,v,rs,ro in secs:
        if ro<=off<ro+rs: return base+v+off-ro
    raise ValueError(hex(off))
runs=[];i=hdr_end
while i<len(a):
    if a[i]!=b[i]:
        j=i
        while j<len(a) and (a[j]!=b[j] or any(a[k]!=b[k] for k in range(j,min(j+8,len(a))))): j+=1
        runs.append((i,j));i=j
    else: i+=1
total=0
with open(out,'w') as f:
    f.write('/* generated by tools/make_patches.py */\n#pragma once\n')
    for k,(s,e) in enumerate(runs):
        f.write(f'static const unsigned char P{k}_old[]={{{",".join(str(x) for x in a[s:e])}}};\n')
        f.write(f'static const unsigned char P{k}_new[]={{{",".join(str(x) for x in b[s:e])}}};\n')
        total+=e-s
    f.write('static const struct patch { unsigned va, len; const unsigned char *old_, *new_; } PATCHES[]={\n')
    for k,(s,e) in enumerate(runs): f.write(f' {{0x{va(s):X},{e-s},P{k}_old,P{k}_new}},\n')
    f.write('};\n#define NPATCHES (sizeof(PATCHES)/sizeof(PATCHES[0]))\n')
print(len(runs),'patches',total,'bytes',[(hex(va(s)),e-s) for s,e in runs])
